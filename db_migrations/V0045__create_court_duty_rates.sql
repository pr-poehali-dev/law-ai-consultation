-- Ставки госпошлины (ст. 333.19 и 333.21 НК РФ)
CREATE TABLE IF NOT EXISTS t_p57945357_law_ai_consultation.court_duty_rates (
    id SERIAL PRIMARY KEY,
    court_type VARCHAR(20) NOT NULL,   -- 'civil' | 'arbitration'
    sub_key VARCHAR(50) NOT NULL,      -- ключ: 'pp6_normative', 'pp7', etc.
    label TEXT NOT NULL,               -- полное название заявления
    sub_ref VARCHAR(60) NOT NULL,      -- ссылка на НК РФ
    amount_individual INTEGER NOT NULL DEFAULT 0,
    amount_org INTEGER NOT NULL DEFAULT 0,
    note TEXT NOT NULL DEFAULT '',     -- доп. примечание (для спец. расчётов)
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_by VARCHAR(100) NOT NULL DEFAULT 'system'
);

CREATE TABLE IF NOT EXISTS t_p57945357_law_ai_consultation.court_duty_history (
    id SERIAL PRIMARY KEY,
    rate_id INTEGER NOT NULL REFERENCES t_p57945357_law_ai_consultation.court_duty_rates(id),
    field_changed VARCHAR(50) NOT NULL,
    old_value TEXT,
    new_value TEXT,
    changed_by VARCHAR(100) NOT NULL,
    changed_at TIMESTAMP NOT NULL DEFAULT NOW()
);

-- Индексы
CREATE INDEX IF NOT EXISTS idx_court_duty_rates_type ON t_p57945357_law_ai_consultation.court_duty_rates(court_type);

