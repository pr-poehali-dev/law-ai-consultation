/**
 * Очистка текста нормативных документов от служебного "мусора" систем типа
 * ГАРАНТ/КонсультантПлюс: пометки "ГАРАНТ:", "Информация об изменениях:",
 * "См. предыдущую редакцию", ссылки на комментарии, сноски об изменениях
 * законодательства и т.п. Это не часть текста самого закона.
 *
 * Источники хранят документы в двух формах — с переносами строк между
 * абзацами и полностью слитые в одну строку (мусор идёт прямо посреди
 * текста статей). Поэтому очистка выполняется через regex по всему тексту
 * (не построчно), с явными границами до следующего пункта/статьи/главы.
 */

const NOISE_PATTERNS: RegExp[] = [
  // "ГАРАНТ: См. ... РФ/Кодекса/закона." — короткая ссылка на комментарии/энциклопедии
  /ГАРАНТ:\s*См\.[^.\n]*?(?:РФ|Кодекса|закона)\.?\s*/gi,
  // "ГАРАНТ: <произвольный текст>" до следующего пункта/статьи/главы/раздела/примечания или конца
  /ГАРАНТ:\s*[\s\S]*?(?=\n|\d+(?:\.\d+)?\.\s|Статья\s+\d|Раздел\s+[IVXLC]|Глава\s+\d|Примечание\.|$)/gi,
  // "О конституционно-правовом смысле ... см. постановление КС РФ N X-П"
  /О конституционно-правовом смысле[^\n]*?(?:см\.)?[^\n]*?(?:N|№)\s*[\d/-]+[-–][ПП]?\s*/gi,
  // 'См. схему "..."'
  /См\.\s*схему\s*"[^"]*"\s*/gi,
  // "О применении судами ... постановление Пленума ... N X"
  /О применении судами[^\n]*?(?:постановление|Пленума)[^\n]*?(?:N|№)\s*[\d/-]+\s*/gi,
  // "См. комментарии/Энциклопедии ... к статье N ... РФ/Кодекса"
  /См\.\s*(?:комментарии|Энциклопедии)[^.\n]*?(?:РФ|Кодекса)\.?\s*/gi,
  // Заголовок блока изменений
  /Информация об изменениях:\s*/gi,
  // "Статья/Часть/Пункт/Подпункт N дополнена/изменена/изложена/исключена ... № X-ФЗ"
  /(?:Статья|Часть|Пункт|Подпункт)\s+[\d.]+\s+(?:дополнен[а]?|изменен[а]?|изложен[а]?|исключен[а]?)\s+[^\n]*?(?:N|№)\s*\d+[-–]ФЗ[^\n]*?(?=\n|$)/gi,
  // "Федеральным законом от ... N/№ X-ФЗ <текст> изложен(о/а)/внесены изменения/дополнен(о/а)"
  /Федеральным законом от\s+[^\n]*?(?:N|№)\s*\d+[-–]ФЗ\s+[^\n]*?(?:изложен[оа]?(?:\s+в новой редакции)?|внесены изменения|дополнен[оа]?)/gi,
  // "Наименование изменено ... № X-ФЗ"
  /Наименование изменено\s+[^\n]*?(?:N|№)\s*\d+[-–]ФЗ\s*/gi,
  // "См. предыдущую редакцию"
  /См\.\s*предыдущую редакцию\s*/gi,
  // "См. текст статьи/части/пункта/подпункта/примечания/наименования ... [в предыдущей редакции]"
  /См\.\s*текст (?:статьи|части|пункта|подпункта|примечания|наименования)[^\n]*?(?=\n|$|\d+(?:\.\d+)?\.\s|Статья\s+\d|Примечание\.)/gi,
  // "действие ... Федеральным законом ... приостановлено"
  /действие\s+Федеральным законом\s+[\s\S]*?приостановлено\s*/gi,
];

/** Убирает служебный мусор источника из текста, возвращает очищенные непустые строки. */
export function splitCleanLines(text: string): string[] {
  let cleaned = text;
  for (const pattern of NOISE_PATTERNS) {
    cleaned = cleaned.replace(pattern, " ");
  }
  return cleaned
    .split("\n")
    .map(l => l.replace(/[ \t]{2,}/g, " ").trim())
    .filter(Boolean);
}

/** Возвращает текст без служебного мусора источника, строки склеены через перевод строки. */
export function cleanLegalText(text: string): string {
  return splitCleanLines(text).join("\n");
}
