def is_duty_query(messages: list) -> bool:
    if not messages:
        return False
    last_user = next((m for m in reversed(messages) if m.get("role") == "user"), None)
    if not last_user:
        return False
    text = (last_user.get("content") or "").lower()
    return any(marker in text for marker in _DUTY_MARKERS)


