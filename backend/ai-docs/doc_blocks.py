BLOCK_BY_DOC_TYPE: dict[str, str] = {}
for _subtypes, _system in _BLOCK_SYSTEMS:
    for _k in _subtypes:
        BLOCK_BY_DOC_TYPE[_k] = _system


def get_system_prompt(doc_type: str, legal_quality_addon: str = "") -> str:
    """Возвращает системный промт для doc_type."""
    if doc_type in BLOCK_BY_DOC_TYPE:
        subtype_hint = ALL_SUBTYPES.get(doc_type, "")
        return (
            BLOCK_BY_DOC_TYPE[doc_type]
            + f"\n\nТип документа: {subtype_hint}"
            + ("\n\n" + legal_quality_addon if legal_quality_addon else "")
        )
    return ""


def get_doc_label(doc_type: str) -> str:
    """Человекочитаемое название документа."""
    return ALL_SUBTYPES.get(doc_type, "документ")
